-- Drop tables (child tables first) so the script can be re-run safely
DROP TABLE IF EXISTS payments, lab_requests, lab_tests, prescription_items,
  prescriptions, medications, diagnoses, appointments, patients, staff,
  departments, branches CASCADE;
 
-- ---------- Reference tables ----------
CREATE TABLE branches (
  branch_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       VARCHAR(50)  NOT NULL UNIQUE,
  address    VARCHAR(200) NOT NULL,
  phone      VARCHAR(20)
);
 
CREATE TABLE departments (
  department_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          VARCHAR(60) NOT NULL UNIQUE
);
 
-- ---------- People ----------
CREATE TABLE staff (
  staff_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name     VARCHAR(50)  NOT NULL,
  last_name      VARCHAR(50)  NOT NULL,
  role           VARCHAR(20)  NOT NULL
                 CHECK (role IN ('Doctor','Receptionist','Lab Technician','Pharmacist','Admin')),
  specialisation VARCHAR(60),
  department_id  INT REFERENCES departments(department_id),
  branch_id      INT NOT NULL REFERENCES branches(branch_id),
  phone          VARCHAR(20),
  email          VARCHAR(100) UNIQUE,
  hire_date      DATE NOT NULL,
  -- every doctor must have a specialisation
  CONSTRAINT chk_doctor_specialisation
    CHECK (role <> 'Doctor' OR specialisation IS NOT NULL)
);
 
CREATE TABLE patients (
  patient_id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name           VARCHAR(50)  NOT NULL,
  last_name            VARCHAR(50)  NOT NULL,
  date_of_birth        DATE NOT NULL CHECK (date_of_birth > DATE '1900-01-01'),
  gender               VARCHAR(10)  NOT NULL CHECK (gender IN ('Male','Female')),
  phone                VARCHAR(20)  NOT NULL,
  email                VARCHAR(100),
  address              VARCHAR(200),
  blood_group          VARCHAR(3)
                       CHECK (blood_group IN ('A+','A-','B+','B-','AB+','AB-','O+','O-')),
  registered_branch_id INT NOT NULL REFERENCES branches(branch_id),
  registered_at        TIMESTAMP NOT NULL DEFAULT now()
);
 
-- ---------- Clinical activity ----------
CREATE TABLE appointments (
  appointment_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id       INT NOT NULL REFERENCES patients(patient_id),
  doctor_id        INT NOT NULL REFERENCES staff(staff_id),
  branch_id        INT NOT NULL REFERENCES branches(branch_id),
  appointment_date DATE NOT NULL,
  start_time       TIME NOT NULL,
  status           VARCHAR(20) NOT NULL DEFAULT 'Booked'
                   CHECK (status IN ('Booked','Completed','Cancelled','No-show')),
  reason           TEXT,
  created_at       TIMESTAMP NOT NULL DEFAULT now()
);
 
-- A doctor cannot be double-booked for the same slot.
-- Partial index: cancelled appointments do not block the slot.
CREATE UNIQUE INDEX uq_doctor_slot
  ON appointments (doctor_id, appointment_date, start_time)
  WHERE status <> 'Cancelled';
 
CREATE TABLE diagnoses (
  diagnosis_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id INT NOT NULL REFERENCES appointments(appointment_id),
  icd10_code     VARCHAR(10),
  description    TEXT NOT NULL,
  diagnosed_at   TIMESTAMP NOT NULL DEFAULT now()
);
 
-- ---------- Pharmacy ----------
CREATE TABLE medications (
  medication_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          VARCHAR(100) NOT NULL,
  form          VARCHAR(30)  NOT NULL
                CHECK (form IN ('Tablet','Capsule','Syrup','Injection','Cream')),
  strength      VARCHAR(30),
  unit_price    NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0),
  UNIQUE (name, form, strength)
);
 
CREATE TABLE prescriptions (
  prescription_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id  INT NOT NULL REFERENCES appointments(appointment_id),
  issued_at       TIMESTAMP NOT NULL DEFAULT now(),
  status          VARCHAR(20) NOT NULL DEFAULT 'Pending'
                  CHECK (status IN ('Pending','Dispensed','Cancelled')),
  dispensed_by    INT REFERENCES staff(staff_id),
  dispensed_at    TIMESTAMP,
  -- a dispensed prescription must record who dispensed it and when
  CONSTRAINT chk_dispensed_details
    CHECK (status <> 'Dispensed' OR (dispensed_by IS NOT NULL AND dispensed_at IS NOT NULL))
);
 
-- Junction table: resolves the many-to-many between prescriptions and medications
CREATE TABLE prescription_items (
  prescription_id INT NOT NULL REFERENCES prescriptions(prescription_id) ON DELETE CASCADE,
  medication_id   INT NOT NULL REFERENCES medications(medication_id),
  dosage          VARCHAR(50) NOT NULL,
  frequency       VARCHAR(50) NOT NULL,
  duration_days   INT NOT NULL CHECK (duration_days > 0),
  quantity        INT NOT NULL CHECK (quantity > 0),
  PRIMARY KEY (prescription_id, medication_id)
);
 
-- ---------- Laboratory ----------
CREATE TABLE lab_tests (
  test_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name    VARCHAR(100) NOT NULL UNIQUE,
  price   NUMERIC(10,2) NOT NULL CHECK (price >= 0)
);
 
CREATE TABLE lab_requests (
  lab_request_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id INT NOT NULL REFERENCES appointments(appointment_id),
  test_id        INT NOT NULL REFERENCES lab_tests(test_id),
  technician_id  INT REFERENCES staff(staff_id),
  status         VARCHAR(20) NOT NULL DEFAULT 'Requested'
                 CHECK (status IN ('Requested','In Progress','Completed')),
  result         TEXT,
  requested_at   TIMESTAMP NOT NULL DEFAULT now(),
  result_at      TIMESTAMP,
  -- a completed test must have a result
  CONSTRAINT chk_completed_has_result
    CHECK (status <> 'Completed' OR result IS NOT NULL)
);
 
-- ---------- Billing ----------
CREATE TABLE payments (
  payment_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id INT NOT NULL REFERENCES appointments(appointment_id),
  amount         NUMERIC(10,2) NOT NULL CHECK (amount > 0),
  method         VARCHAR(20) NOT NULL
                 CHECK (method IN ('Cash','Card','Transfer','HMO')),
  status         VARCHAR(20) NOT NULL DEFAULT 'Paid'
                 CHECK (status IN ('Paid','Pending','Refunded','Failed')),
  paid_at        TIMESTAMP NOT NULL DEFAULT now()
);
